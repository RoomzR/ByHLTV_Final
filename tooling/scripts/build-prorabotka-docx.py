def set_run(run, *, size=11, bold=False, color=INK, font="Calibri", italic=False):
    run.font.name = font
    run._element.rPr.rFonts.set(qn("w:eastAsia"), font)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    run.font.color.rgb = color


def add_text(p, text, **kwargs):
    run = p.add_run(text)
    set_run(run, **kwargs)
    return run


def shade(cell, hex_color: str):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    for old in tcPr.findall(qn("w:shd")):
        tcPr.remove(old)
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), hex_color)
    shd.set(qn("w:val"), "clear")
    tcPr.append(shd)


def set_cell_border(cell):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcBorders = OxmlElement("w:tcBorders")
    for edge in ("top", "left", "bottom", "right"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:space"), "0")
        el.set(qn("w:color"), LINE)
        tcBorders.append(el)
    for old in tcPr.findall(qn("w:tcBorders")):
        tcPr.remove(old)
    tcPr.append(tcBorders)


def set_cell_margins(cell, dxa=60):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcMar = OxmlElement("w:tcMar")
    for m in ("top", "left", "bottom", "right"):
        node = OxmlElement(f"w:{m}")
        node.set(qn("w:w"), str(dxa))
        node.set(qn("w:type"), "dxa")
        tcMar.append(node)
    for old in tcPr.findall(qn("w:tcMar")):
        tcPr.remove(old)
    tcPr.append(tcMar)


def prevent_row_split(row):
    tr = row._tr
    trPr = tr.get_or_add_trPr()
    cant = OxmlElement("w:cantSplit")
    trPr.append(cant)


def fill_cell(cell, text, *, bold=False, size=10, color=INK, align="left", bg=None):
    cell.text = ""
    set_cell_border(cell)
    set_cell_margins(cell)
    if bg:
        shade(cell, bg)
    p = cell.paragraphs[0]
    p.alignment = {
        "left": WD_ALIGN_PARAGRAPH.LEFT,
        "center": WD_ALIGN_PARAGRAPH.CENTER,
        "right": WD_ALIGN_PARAGRAPH.RIGHT,
    }[align]
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(0)
    p.paragraph_format.line_spacing = 1.15
    add_text(p, text, size=size, bold=bold, color=color)


def make_table(doc, headers, rows, col_widths=None, money_cols=None):
    money_cols = set(money_cols or [])
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    hdr = table.rows[0]
    prevent_row_split(hdr)
    for i, h in enumerate(headers):
        fill_cell(hdr.cells[i], h, bold=True, size=10, color=WHITE, bg=HEAD_BG, align="center")
    for r_i, row in enumerate(rows):
        wr = table.rows[r_i + 1]
        prevent_row_split(wr)
        bg = ZEBRA if r_i % 2 else "FFFFFF"
        last = r_i == len(rows) - 1 and any("итого" in str(c).lower() for c in row[:1])
        if last:
            bg = ACCENT_BG
        for c_i, val in enumerate(row):
            align = "right" if c_i in money_cols else "left"
            fill_cell(
                wr.cells[c_i],
                str(val),
                bold=last or (c_i == 0),
                size=10,
                align=align,
                bg=bg,
            )
    if col_widths:
        for row in table.rows:
            for i, w in enumerate(col_widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()
    return table


def p_style(p, *, after=8, before=0, align="left"):
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    p.paragraph_format.line_spacing = 1.15
    p.alignment = {
        "left": WD_ALIGN_PARAGRAPH.LEFT,
        "center": WD_ALIGN_PARAGRAPH.CENTER,
        "justify": WD_ALIGN_PARAGRAPH.JUSTIFY,
    }[align]
    return p


def body(doc, text, *, after=8):
    p = p_style(doc.add_paragraph(), after=after, align="justify")
    add_text(p, text, size=11)
    return p


def bullet(doc, text):
    p = p_style(doc.add_paragraph(), after=4)
    p.style = doc.styles["List Bullet"]
    if p.runs:
        p.runs[0].text = text
        set_run(p.runs[0], size=11)
    else:
        add_text(p, text, size=11)
    for run in p.runs:
        set_run(run, size=11)


def heading(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    for run in p.runs:
        set_run(run, size=16 if level == 1 else 13 if level == 2 else 12, bold=True, color=NAVY)
    p.paragraph_format.space_before = Pt(16 if level == 1 else 12)
    p.paragraph_format.space_after = Pt(8)
    return p


def caption(doc, text):
    p = p_style(doc.add_paragraph(), after=10, before=-6)
    add_text(p, text, size=9, italic=True, color=MUTED)


