function run(text, opts = {}) {
  return new TextRun({
    text: String(text),
    font: "Calibri",
    size: opts.size ?? 22,
    bold: !!opts.bold,
    italics: !!opts.italic,
    color: opts.color ?? INK,
  });
}

function para(text, opts = {}) {
  return new Paragraph({
    spacing: { after: opts.after ?? 160, before: opts.before ?? 0, line: 276 },
    alignment: opts.align ?? AlignmentType.JUSTIFIED,
    children: [run(text, opts)],
  });
}

function h(text, level) {
  const size = level === 1 ? 32 : level === 2 ? 26 : 24;
  return new Paragraph({
    heading: level === 1 ? HeadingLevel.HEADING_1 : level === 2 ? HeadingLevel.HEADING_2 : HeadingLevel.HEADING_3,
    spacing: { before: level === 1 ? 360 : 280, after: 140 },
    children: [run(text, { bold: true, size, color: NAVY })],
  });
}

function caption(text) {
  return para(text, { size: 18, italic: true, color: MUTED, after: 200, align: AlignmentType.LEFT });
}

function cell(text, opts = {}) {
  const fill = opts.header ? NAVY : opts.total ? TOTAL : opts.zebra ? ZEBRA : "FFFFFF";
  return new TableCell({
    borders,
    width: { size: opts.width, type: WidthType.DXA },
    shading: { type: ShadingType.CLEAR, fill },
    margins: { top: 60, bottom: 60, left: 80, right: 80 },
    verticalAlign: VerticalAlign.CENTER,
    children: [
      new Paragraph({
        alignment: opts.align ?? AlignmentType.LEFT,
        spacing: { after: 0, before: 0, line: 240 },
        children: [
          run(text, {
            size: 20,
            bold: !!(opts.header || opts.bold || opts.total),
            color: opts.header ? WHITE : INK,
          }),
        ],
      }),
    ],
  });
}

function table(headers, rows, colPct, moneyCols = []) {
  const widths = colPct.map((p) => Math.round((PAGE * p) / 100));
  const money = new Set(moneyCols);
  const isTotal = (row) => /итого|это примерно/i.test(String(row[0]));
  const headerRow = new TableRow({
    cantSplit: true,
    tableHeader: true,
    children: headers.map((h, i) =>
      cell(h, {
        header: true,
        width: widths[i],
        align: AlignmentType.CENTER,
      }),
    ),
  });
  const body = rows.map((row, r) => {
    const total = isTotal(row);
    return new TableRow({
      cantSplit: true,
      children: row.map((val, i) =>
        cell(val, {
          width: widths[i],
          zebra: !total && r % 2 === 1,
          total,
          bold: i === 0,
          align: money.has(i) ? AlignmentType.RIGHT : AlignmentType.LEFT,
        }),
      ),
    });
  });
  return new Table({
    width: { size: PAGE, type: WidthType.DXA },
    columnWidths: widths,
    rows: [headerRow, ...body],
  });
}

